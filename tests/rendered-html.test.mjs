import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const developmentPreviewMeta =
  /<meta(?=[^>]*\bname=["']codex-preview["'])(?=[^>]*\bcontent=["']development["'])[^>]*>/i;

test("renders development preview metadata", async () => {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);

  const response = await worker.fetch(
    new Request("http://localhost/en", {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async () => new Response("Not found", { status: 404 }),
      },
    },
    {
      waitUntil() {},
      passThroughOnException() {},
    },
  );

  assert.equal(response.status, 200);
  assert.match(
    response.headers.get("content-type") ?? "",
    /^text\/html\b/i,
  );
  assert.match(await response.text(), developmentPreviewMeta);
});

test("drives each feature object from its panel scroll timeline", async () => {
  const css = await readFile(
    new URL("../app/globals.css", import.meta.url),
    "utf8",
  );

  assert.match(css, /\.coin\s*\{[^}]*animation-timeline:\s*--story-panel/s);
  assert.match(css, /\.dice\s*\{[^}]*animation-timeline:\s*--story-panel/s);
  assert.match(css, /\.card-stack\s*\{[^}]*animation-timeline:\s*--story-panel/s);
  assert.match(css, /\.list-orbit\s*\{[^}]*animation-timeline:\s*--story-panel/s);
  assert.doesNotMatch(css, /scroll-snap-stop:\s*always/);
});
